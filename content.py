def _nl_date(iso):
    months = ["januari", "februari", "maart", "april", "mei", "juni", "juli",
              "augustus", "september", "oktober", "november", "december"]
    y, m, d = iso.split("-")
    return f"{int(d)} {months[int(m)-1]} {y}"


